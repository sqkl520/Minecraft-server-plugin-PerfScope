/**
 * 报告层文案表（HTML / TXT / 控制台日志）。
 *
 * <p><b>为什么单独一个类</b>：与 {@code CoreMessages} 同样的理由——报告层有近百条文案，
 * 全部塞进 {@link Messages} 的静态块会让它成为唯一的写入热点，多个改造任务无法并行。
 * 本类在 static 块里把自己的中英文表交给 {@link Messages#registerModule}，
 * 合并结果与"直接写在 Messages 里"完全等价（同一张表、同样的两级回退、同样的 messages.yml 覆盖）。</p>
 *
 * <p><b>键空间划分</b>：</p>
 * <ul>
 *   <li>{@code report.html.*} —— 只出现在 HTML 报告里的文案（标题、表头、卡片副标题）；</li>
 *   <li>{@code report.txt.*} —— 只出现在 TXT 报告里的文案（段落头、整行模板）；</li>
 *   <li>{@code report.common.*} —— 两种格式共用（"不可用""未知""生成时间"）；</li>
 *   <li>{@code report.log.*} —— 报告层写控制台的告警（控制台也是给人看的界面，
 *       同样随 {@code general.language} 整份切换）。</li>
 * </ul>
 *
 * <p><b>JSON 报告刻意没有文案键</b>：{@code perfscope-*.json} 的字段名与字面值
 * （{@code tps} / {@code mspt} / {@code unavailable} / {@code ok} / {@code degraded} /
 * {@code tick_times} / {@code avg_tick} …）是下游巡检脚本、Grafana 抓取与 CI 门禁依赖的
 * <b>外部契约</b>，绝不随语言变化。报告里唯一与语言相关的 JSON 内容是
 * {@code alerts.critical[]} / {@code alerts.warnings[]} 里的自然语言句子，
 * 它们由告警层（{@code Alert.message()}）产出，不属于本类。</p>
 *
 * <p><b>占位符</b>：{@code {0}}、{@code {1}}…… 由 {@link Messages#get(String, Object...)} 按序号替换。
 * 数值一律先由调用点格式化成字符串再传入——报告里的数字是数据，格式（两位小数、百分号位置）
 * 不能因为翻译而改变。</p>
 *
 * <p><b>两种语言键集合必须一致</b>：{@link #put} 同时写两张表，从结构上保证不会漏翻一边
 * （漏一边的后果是该语言下直接显示键名）。</p>
 */
