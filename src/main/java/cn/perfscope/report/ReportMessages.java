    /**
     * 确保报告层文案已并入当前语言快照；未并入时补一次 {@link Messages#load}。
     *
     * <p>只在 {@link ReportGenerator} 构造时调用。正常路径（哨兵键已在表中）直接返回，
     * 不会产生任何额外 IO 或日志。</p>
     */
    public static void ensureRegistered(PerfScope plugin) {
        if (Messages.keys().contains(SENTINEL_KEY) || plugin == null) {
            return;
        }
        try {
            // load 内部会 touchModules + mergeModules，把本类（及同时期注册的其它模块）
            // 的键并进默认表，随后原子发布新的语言快照。
            Messages.load(plugin);
        } catch (Exception | LinkageError e) {
            // f-s05-err-06：catch 体此前只有注释，失败后 report.* 全部回退为键名（报告正文里
            // 出现 "report.html.title" 这类文本），而控制台没有任何"为什么"——注释所称
            // "可见、可排查"仅在用户打开报告时才成立。此处补一条 WARNING，仍不阻止启动。
            // 注意：本分支的典型成因就是键表没合并成功，此时 Messages.get 会退回键名本身，
            // 故必须再判一次，否则"解释"本身也变成一串键名。
            String msg = Messages.get("report.log.register-failed", e);
            if (msg.startsWith("report.log.")) {
                msg = "[PerfScope] Failed to merge report messages; report text will fall back to raw keys: " + e;
            }
            plugin.getLogger().warning(msg);
        }
    }

    private static void put(Map<String, String> en, Map<String, String> zh,
                            String key, String enValue, String zhValue) {
        en.put(key, enValue);
        zh.put(key, zhValue);
    }

    private ReportMessages() {}
